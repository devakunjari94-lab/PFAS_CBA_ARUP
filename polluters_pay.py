with st.expander("ℹ️ What does 'Uncertainty' mean?"):
    st.markdown("""
### Why uncertainty exists

PFAS treatment costs are not fixed values.

They vary depending on:
- site conditions  
- water quality  
- system design  
- contractor approach  

---

### What this slider does

The uncertainty slider allows you to move **between best and worst case costs**:

- **0% → Best case**
  - ideal conditions  
  - low energy, low waste  

- **50% → Typical case**
  - average real-world scenario  

- **100% → Worst case**
  - difficult water  
  - high waste disposal costs  

---

### How to use it

- Use **50%** for general comparison  
- Use **low values** if site is straightforward  
- Use **high values** for risk or worst-case planning  

---

### Key idea

👉 Instead of one “exact” cost, this tool shows a **range of possible costs**.
""")
